from __future__ import annotations

import logging

from langchain_openai import ChatOpenAI
from pydantic import BaseModel, Field

from kb.retrieve import retrieve_from_conditions

logger = logging.getLogger(__name__)

_MODEL = "gpt-4o-mini"
# Was 2. Raised to 3 after manual testing found a real miss: a generic query like "what is
# neurodevelopmental syndrome" ranked the BLBS2 entry 3rd (embedding similarity is semantic,
# not keyword matching — BLBS2's entry is dense with genetics terminology, which pulls its
# embedding away from plain-language phrasing even though its own name contains the exact
# words "neurodevelopmental syndrome"). With only 6 entries in this KB, the extra chunk per
# query is a cheap way to buy margin against this kind of near-miss; worth revisiting if KB1
# grows much larger, where a wider top_k would just add noise instead of catching edge cases.
_TOP_K = 3

_SYSTEM_PROMPT = """You are the Info Agent for NorthStar, a navigator — not a clinician — for \
parents of neurodivergent children. Answer the parent's question using ONLY the knowledge base \
excerpts below. Do not use outside knowledge.

Rules:
- Never use diagnostic language (e.g. "your child has X"). Explain conditions/terms in general terms.
- If the excerpts don't actually address the question, say so plainly in your explanation instead \
of guessing — do not invent information.
- Always write a disclaimer reminding the parent this is general information, not a diagnosis, and \
that a qualified specialist (e.g. a developmental pediatrician) should be consulted for concerns \
about their own child.
- Keep the explanation grounded, warm, and in plain language — avoid clinical jargon where possible.
- BE CONCISE: 3-4 sentences, covering only the single most useful point for a parent asking this \
exact question — not everything the excerpts contain. PRESS_RELEASE_AND_FAQ.md describes parents \
as "time-poor and emotionally stretched"; a shorter, well-chosen answer serves them better than a \
complete one. (Real feedback from a test parent flagged a prior answer as too long — see \
feedback.jsonl and BUILD_LOG.md's Day 7 entry.)

Condition under discussion, if known from earlier in this conversation (helps interpret a vague \
follow-up like "tell me more about that" — ignore this if it conflicts with what the CURRENT \
question is actually asking): {condition_hint}

Knowledge base excerpts:
{context}"""


class _InfoLLMOutput(BaseModel):
    """What the LLM produces; retrieval provenance is attached afterward, not generated by the model."""

    topic: str = Field(description="The condition or term the question is about.")
    explanation: str = Field(description="Grounded, plain-language explanation based only on the excerpts.")
    disclaimer: str = Field(description="Reminder that this is general info, not a diagnosis; consult a specialist.")


class InfoOutput(BaseModel):
    """Grounded explanation of a condition or term, with retrieval provenance for transparency."""

    topic: str
    explanation: str
    retrieved_chunks: list[str] = Field(description="Human-readable text of the KB entries used as context.")
    source_ids: list[str] = Field(description="KB entry ids used as context, e.g. ['autism-spectrum-disorder'].")
    disclaimer: str


_llm = ChatOpenAI(model=_MODEL, temperature=0).with_structured_output(
    _InfoLLMOutput, method="function_calling"
)


def _format_entry(entry: dict) -> str:
    """Render a conditions.json entry as plain text for LLM context and transparency display."""
    # entry.items() gives (key, value) pairs for every field in the JSON object. We skip "id"
    # (an internal identifier, not useful content) and join everything else into one blob of
    # text — this is what actually gets embedded for retrieval and shown to the LLM as context.
    terms = "; ".join(f"{t['term']}: {t['definition']}" for t in entry.get("terminology", []))
    return (
        f"{entry['name']}. Overview: {entry['overview']} "
        f"Common signs: {', '.join(entry.get('common_signs', []))}. "
        f"Terminology: {terms}. "
        f"What we don't cover: {entry.get('what_we_dont_cover', '')}"
    )


def explain(query: str, condition_hint: str | None = None) -> InfoOutput:
    """Answer a parent's info-intent question, grounded in the Conditions + Terminology KB.

    `condition_hint` (optional) is the condition the Router resolved for this turn — possibly
    from the CURRENT message, possibly carried forward from earlier in the conversation (see
    agents/router.py's history-awareness). main.py passes it through unconditionally; every
    other caller (CLI, eval.py) doesn't supply one, which behaves exactly as before this change.
    """
    logger.info(f"Info Agent: answering query: {query!r} condition_hint={condition_hint!r}")

    # Retrieval happens BEFORE the LLM call and its results are kept separately (retrieved_chunks,
    # source_ids below) rather than asked of the model. This is deliberate: if we asked the LLM
    # to also report which chunks it used, it could misreport or fabricate that — and the press
    # release's "grounded answers, with sources you can inspect" promise depends on those being
    # real, not model-generated.
    #
    # retrieval_query (condition_hint prepended) is used ONLY for the embedding search below —
    # it never replaces `query` itself, which is still what's sent to the LLM as the actual
    # human message. This gives a vague follow-up ("tell me more about that") a real condition
    # name to search the KB against, without changing what the parent is understood to have asked.
    retrieval_query = f"{condition_hint} {query}" if condition_hint else query
    entries = retrieve_from_conditions(retrieval_query, top_k=_TOP_K)
    retrieved_chunks = [_format_entry(entry) for entry in entries]
    source_ids = [entry["id"] for entry in entries]

    # Build the actual prompt by inserting the retrieved text where {context} was in the template.
    context = "\n\n".join(retrieved_chunks)
    prompt = _SYSTEM_PROMPT.format(context=context, condition_hint=condition_hint or "(none)")
    result = _llm.invoke([("system", prompt), ("human", query)])

    logger.info(f"Info Agent: topic={result.topic} sources={source_ids}")
    # Assemble the PUBLIC output here: the LLM only ever supplied topic/explanation/disclaimer
    # (_InfoLLMOutput); retrieved_chunks and source_ids are bolted on from the retrieval step
    # we did ourselves above, not from result.
    return InfoOutput(
        topic=result.topic,
        explanation=result.explanation,
        retrieved_chunks=retrieved_chunks,
        source_ids=source_ids,
        disclaimer=result.disclaimer,
    )
